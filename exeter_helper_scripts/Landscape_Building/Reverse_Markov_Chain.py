import numpy as np


def reverse_markov_chain(P, start_patch, n_steps, initial_distribution=None):
    """
    Run a Markov chain forward, then trace backwards from a chosen
    patch in the final state.

    Parameters
    ----------
    P : np.ndarray
        Row-normalised transition matrix.
        P[i, j] = probability of moving from patch i to patch j.

    start_patch : int
        Patch to condition on at the final timestep.

    n_steps : int
        Number of forward/backward Markov steps.

    initial_distribution : np.ndarray, optional
        Distribution at time 0.
        If None, starts with equal probability in every patch.

    Returns
    -------
    backward_distributions : np.ndarray
        Shape (n_steps + 1, n_patches).

        backward_distributions[t, i] is the probability that an
        individual currently in `start_patch` at the final timestep
        was in patch i at timestep t.

    forward_distributions : np.ndarray
        The forward population distribution at every timestep.
    """

    n_patches = P.shape[0]

    # ---------------------------------------------------------
    # Check matrix
    # ---------------------------------------------------------

    if P.shape != (n_patches, n_patches):
        raise ValueError("P must be a square matrix.")

    if not np.allclose(P.sum(axis=1), 1):
        raise ValueError("Rows of P must sum to 1.")

    if not (0 <= start_patch < n_patches):
        raise ValueError("start_patch is outside the range of patches.")

    # ---------------------------------------------------------
    # Initial distribution
    # ---------------------------------------------------------

    if initial_distribution is None:
        initial_distribution = np.ones(n_patches) / n_patches
    else:
        initial_distribution = np.asarray(initial_distribution, dtype=float)
        initial_distribution /= initial_distribution.sum()

    # ---------------------------------------------------------
    # Run chain forward
    # ---------------------------------------------------------

    forward_distributions = np.zeros(
        (n_steps + 1, n_patches)
    )

    forward_distributions[0] = initial_distribution

    for t in range(n_steps):
        forward_distributions[t + 1] = (
            forward_distributions[t] @ P
        )

    # ---------------------------------------------------------
    # Start at the chosen final patch
    # ---------------------------------------------------------

    backward_distributions = np.zeros(
        (n_steps + 1, n_patches)
    )

    backward_distributions[n_steps, start_patch] = 1.0

    # ---------------------------------------------------------
    # Work backwards
    # ---------------------------------------------------------

    for t in range(n_steps - 1, -1, -1):

        current_patch_distribution = backward_distributions[t + 1]

        previous_distribution = np.zeros(n_patches)

        for j in range(n_patches):

            # We currently have probability of being in patch j
            current_prob = current_patch_distribution[j]

            if current_prob == 0:
                continue

            # Forward probability distribution at previous time
            p_previous = forward_distributions[t]

            # Probability of arriving at j
            probability_arriving_at_j = (
                p_previous @ P[:, j]
            )

            if probability_arriving_at_j == 0:
                continue

            # Bayes:
            #
            # P(X_t=i | X_{t+1}=j)
            #
            # = P(X_t=i) P(i -> j)
            #   --------------------
            #       P(X_{t+1}=j)

            reverse_probabilities = (
                p_previous * P[:, j]
                / probability_arriving_at_j
            )

            previous_distribution += (
                current_prob * reverse_probabilities
            )

        backward_distributions[t] = previous_distribution

    return backward_distributions, forward_distributions



